"""w24_evidence.py -- bring w22_evidence.json's letter-case records to what
w22_evidence.py now writes (R23), file -> file. Wave 24; authoring-only.

w22_evidence.main() rebuilds every record from the alignment record in the
render dir, which is transient (it is regenerated by w22_scan/w22_align, an
OCR pass over 180 pages). The letter-case records need nothing from it but the
scan page, so this rewrites ONLY the ':case:' records, from
w22_case_keys.json, with the page each record already carries or -- for the
eleven new possessive records -- the page of Wave 22's eye record
(w22_eye.txt, which read every verse). Every other record is left as it is.

    python3 ingest/w24_evidence.py
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import w22_evidence as E

EV = os.path.join(HERE, 'w22_evidence.json')


def eye_pages():
    out = {}
    for ln in open(os.path.join(HERE, 'w22_eye.txt'), encoding='utf-8'):
        m = re.match(r'^(\d+:\d+)\tp(\d+)\t', ln)
        if m and m.group(1) not in out:
            out[m.group(1)] = int(m.group(2))
    return out


def main():
    ev = json.load(open(EV, encoding='utf-8'))
    old = {k: v for k, v in ev.items() if ':case:' in k}
    pages = eye_pages()
    keys = json.load(open(os.path.join(HERE, 'w22_case_keys.json'), encoding='utf-8'))
    new = {}
    for k in keys:
        ref = '%d:%d' % (k['psalm'], k['verse'])
        tag = '%s:case:%s' % (ref, k['id'])
        page = old[tag]['page'] if tag in old else pages[ref]
        new[tag] = dict({'page': page, 'eye': k['book'], 'cell': k['cell'], 'kind': k['kind'],
                         'strip': k['strip'], 'group': k['group'],
                         'note': E.CASE_NOTE[k['group']]}, **E.CASE_EXTRA.get(k['group'], {}))
    gone = set(old) - set(new)
    if gone:
        raise SystemExit('case records with no key: %s' % sorted(gone)[:5])
    for tag, rec in old.items():       # nothing but the note may change on a Wave-22 record
        a = {x: y for x, y in rec.items() if x != 'note'}
        b = {x: y for x, y in new[tag].items() if x != 'note'}
        if a != b:
            raise SystemExit('%s: record changed beyond its note: %s -> %s' % (tag, a, b))
    ev.update(new)
    json.dump(ev, open(EV, 'w', encoding='utf-8'), indent=1, ensure_ascii=False, sort_keys=True)
    print('%d evidence records (%d letter case: %d re-noted, %d new) -> %s'
          % (len(ev), len(new), len(old), len(new) - len(old), EV))


if __name__ == '__main__':
    main()
