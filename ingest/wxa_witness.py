"""wxa_witness.py -- the 1979 cells corrected against Church Publishing's own
file: every keyed correction, grouped so that a ruling can switch a class on
or off. NOTHING IS ENABLED: apply() is not wired to any build, and
`ENABLED = []` means wxa_apply.py writes no change until a ruling fills it.

THE WITNESS is the publisher's PDF of the 1979 book (see w19_witness.py and
R11); THE CARRIER is justus's 1993 e-text. The witness is a composite: pp.
19-30 (Calendar, 2008) and 889-932 (the RCL, 2007) are later inserts and
settle nothing here, so no item touches tables/calendar.md or
tables/eucharistic-lectionary.md (wxa_gates.py enforces it).

THE ITEMS are data, generated by wxa_items.py into wxa_witness_items.py and
evidenced in wxa_evidence.json (each with its book page). An item is keyed
to the reading it replaces: `old` is a short stretch of the paragraph that
begins at base line `line` (the cell at the branch base, 710f635b...),
taken with at least one unchanged word on each side and widened until it
occurs exactly once in that paragraph; `anchor` is that paragraph's first
words. A restored passage's `new` text was cut from the book's page text by
the script -- it never passed through anyone's hands.

GROUPS (application order):
  MARKUP         the e-text's own markup normalized (=x=, &N., &V./&R.,
                 broken **Label* :, *Label*, [[ ]], &mdash./&3em. -> the
                 book's blank, end-of-file marker, stray '>')     ruling 7
  WORDS          d1-d7 keyed word corrections                     ruling 1
  SPELLING       f spelling / word division                       ruling 1
  PASSAGES       d8/d9 restored or replaced passages, the eight absent
                 collects (and their flags), the Lord's Prayer     ruling 2
  HEADINGS       two misspelt headings (slugs kept, R5)           ruling 9
  MEDIANT_STOPS  h1 the stop before the mediant                   ruling 3
  RUBRIC_STOPS   c  a rubric's final stop as the book prints it   ruling 4
  PUNCT          h2 other stops, never next to the mediant        ruling 5
  DOL_ROWS       lost headings, merged/lost rows (11 flags close) ruling 10
  DOL_FIX        cell-evident citations, abbreviation stops       ruling 10
  DOL_MARKS      the e-text's [*] / && -> the book's marks        ruling 10
  DOL_XMAS       Year Two Christmas block: Year Two's Epistle/Gospel
  DOL_DISPUTED   numeral disputes the second check settles for the book
                 (other year / same citation elsewhere / continuity)
"""
import collections
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from wxa_witness_items import ITEMS

BASE = '710f635b7783f1e8188fa334ec75dca3e43a0220'
GROUP_ORDER = ['MARKUP', 'WORDS', 'SPELLING', 'PASSAGES', 'HEADINGS',
               'MEDIANT_STOPS', 'RUBRIC_STOPS', 'PUNCT', 'DOL_ROWS', 'DOL_FIX',
               'DOL_MARKS', 'DOL_XMAS', 'DOL_DISPUTED']
# Switched on by a ruling, never by default.
ENABLED = []
COMMENT = re.compile(r'<!--.*?-->', re.S)


def blocks(text):
    """[(first line (1-based), number of lines, exact text)] -- runs of
    non-blank lines; the same split wxa_items.py keyed the items to."""
    out, cur, start = [], [], None
    lines = text.split('\n')
    for i, line in enumerate(lines + [''], 1):
        if line.strip():
            if not cur:
                start = i
            cur.append(line)
            continue
        if cur:
            out.append((start, len(cur), '\n'.join(cur)))
            cur = []
    return out


def anchor_of(t):
    return ' '.join(COMMENT.sub('', t).split()[:8])


def items_for(rel, groups):
    for g in GROUP_ORDER:
        if g not in groups:
            continue
        for it in ITEMS.get(g, []):
            if it['file'] == rel:
                yield g, it


def apply(rel, text, groups, strict=True):
    """Apply the enabled groups to one cell's text (its branch-base text).
    Each item: its paragraph is the base block at item['line'] whose first
    words are item['anchor']; item['old'] must occur EXACTLY ONCE in that
    paragraph's current text, or the item is stale and nothing is written
    (strict) / it is skipped and reported (not strict).
    -> (new text, applied [(group, id)], stale [(group, id, why)])"""
    bl = blocks(text)
    by_line = {b[0]: i for i, b in enumerate(bl)}
    cur = [b[2] for b in bl]
    applied, stale = [], []
    for g, it in items_for(rel, groups):
        i = by_line.get(it['line'])
        if i is None or anchor_of(bl[i][2]) != it['anchor']:
            stale.append((g, it['id'], 'paragraph not found at base line'))
            continue
        n = cur[i].count(it['old'])
        if n != 1:
            stale.append((g, it['id'], 'old occurs %d times' % n))
            continue
        cur[i] = cur[i].replace(it['old'], it['new'], 1)
        applied.append((g, it['id']))
    if stale and strict:
        raise SystemExit('wxa_witness: %d stale item(s) in %s, nothing '
                         'written: %s' % (len(stale), rel, stale[:3]))
    # reassemble: each base block's lines replaced by its current text; a
    # block emptied (a dropped flag, the e-text's end marker) takes the
    # blank line after it with it
    lines = text.split('\n')
    out, ln = [], 1
    starts = {b[0]: (b[1], k) for k, b in enumerate(bl)}
    skip_blank = False
    while ln <= len(lines):
        if ln in starts:
            nlines, k = starts[ln]
            if cur[k] == '':
                skip_blank = True
            else:
                out.append(cur[k])
                skip_blank = False
            ln += nlines
            continue
        if skip_blank and lines[ln - 1].strip() == '':
            skip_blank = False
            ln += 1
            continue
        skip_blank = False
        out.append(lines[ln - 1])
        ln += 1
    return '\n'.join(out), applied, stale


def files(groups=None):
    gs = groups or GROUP_ORDER
    return sorted(set(it['file'] for g in gs for it in ITEMS.get(g, [])))


def counts():
    c = collections.Counter()
    for g, v in ITEMS.items():
        for it in v:
            c[(g, it['class'])] += 1
    return c
